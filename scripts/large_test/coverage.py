"""The table that says which feature each question demonstrates and how the result is judged, written from the book
itself, so a feature without a question shows.

    python scripts/large_test/coverage.py --library data/large-test/library --out docs/test-reports/large-test/FEATURES.md
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from large_test import features as F  # noqa: E402

# Features that are counted from the format of the questions, not from questions of their own.
DIMENSIONS = {"T15": "xlsx", "T16": "csv", "T17": "ods"}


def render(questions: list, manifest: dict) -> str:
    by_feature = defaultdict(list)
    for q in questions:
        by_feature[q["feature"]].append(q["id"])
    formats = Counter(q["format"] for q in questions if q["block"] == "spreadsheets")
    lines = [
        "# Features of the application and the questions that demonstrate them", "",
        "Generated by `scripts/large_test/coverage.py` from the book (`questions.json`). A feature of the restart state of "
        "16 October 2026 that is missing from this table is a defect of the test. The features of the set-aside branches "
        "(passage blocks, summaries, dates and amounts as facts, the refusal check, the reranker) do not exist in this "
        "build and are not listed.", "",
        f"The book: {manifest['questions']} questions ({manifest['questions_by_block']}).", "",
    ]
    for block in ("documents", "spreadsheets", "mixed"):
        lines += [f"## {block.capitalize()}", "", "| Feature | What it is | Questions | How the result is judged |", "| --- | --- | --- | --- |"]
        for feature, (owner, name, what, judged) in F.FEATURES.items():
            if owner != block:
                continue
            if feature in DIMENSIONS:
                count = formats[DIMENSIONS[feature]]
                lines.append(f"| {feature} {name} | {what} | {count} (the {DIMENSIONS[feature]} questions of the block) | {judged} |")
                continue
            ids = by_feature.get(feature, [])
            shown = f"{len(ids)}: {', '.join(ids[:6])}{' ...' if len(ids) > 6 else ''}" if ids else "**none**"
            lines.append(f"| {feature} {name} | {what} | {shown} | {judged} |")
        lines.append("")
    lines += ["## Checked by hand in the script", "",
              "These are buttons and displays, not questions. The owner's script (README, section 7) has a step for each.", "",
              "| Control | What to look at |", "| --- | --- |"]
    lines += [f"| {name} | {what} |" for name, what in F.BY_HAND.items()]
    missing = [f for f in F.FEATURES if f not in by_feature and f not in DIMENSIONS]
    lines += ["", "## Features with no question", ""]
    lines += [f"- {f} {F.FEATURES[f][1]}" for f in missing] or ["None."]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--library", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    questions = json.loads((args.library / "questions.json").read_text(encoding="utf-8"))
    manifest = json.loads((args.library / "manifest.json").read_text(encoding="utf-8"))
    args.out.write_text(render(questions, manifest), encoding="utf-8")
    print(f"written {args.out}")


if __name__ == "__main__":
    main()
